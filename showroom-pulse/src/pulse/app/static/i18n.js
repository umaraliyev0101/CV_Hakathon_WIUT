const DICTS = { en, uz, ru };
const LANGS = [["en", "EN", "English"], ["uz", "O'Z", "O'zbekcha"], ["ru", "РУ", "Русский"]];
const HTML_LANG = { en: "en", uz: "uz", ru: "ru" };
const KEY = "pulse.lang";
let lang = "en";
const listeners = [];

export function getLang() { return lang; }

// t("key", {name: value}): current language, falling back to English, then to the key itself.
export function t(key, vars) {
  const s = DICTS[lang][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

export function onLangChange(fn) { listeners.push(fn); }

// Static markup: data-i18n="key" sets textContent; data-i18n-attr="attr:key;attr2:key2" sets attributes.
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
  root.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    for (const pair of el.getAttribute("data-i18n-attr").split(";")) {
      const [attr, key] = pair.split(":");
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
  });
}

function mountSwitcher() {
  const box = document.getElementById("lang-switch");
  if (!box) return;
  box.setAttribute("role", "group");
  box.setAttribute("aria-label", t("lang.aria"));
  box.textContent = "";
  for (const [code, label, name] of LANGS) {
    const b = document.createElement("button");
    b.type = "button"; b.textContent = label;
    b.setAttribute("lang", HTML_LANG[code]); b.setAttribute("title", name);
    b.setAttribute("aria-pressed", String(code === lang));
    b.addEventListener("click", () => setLang(code));
    box.append(b);
  }
}

export function setLang(code, persist = true) {
  if (!Object.hasOwn(DICTS, code)) code = "en";
  lang = code;
  document.documentElement.setAttribute("lang", HTML_LANG[code]);
  if (persist) { try { localStorage.setItem(KEY, code); } catch { /* storage unavailable */ } }
  applyStatic();
  mountSwitcher();
  for (const fn of listeners) { try { fn(code); } catch (e) { console.error(e); } }
}

function init() {
  let saved = null;
  try { saved = localStorage.getItem(KEY); } catch { /* storage unavailable */ }
  setLang(Object.hasOwn(DICTS, saved) ? saved : "en", false);
}
init();
